export function lookupCityCoords(city?: string | null): [number, number] | null {
  if (!city) return null;
  const trimmed = String(city).trim();
  if (TR_CITY_COORDS[trimmed]) return TR_CITY_COORDS[trimmed];
  // Case-insensitive fallback
  const key = Object.keys(TR_CITY_COORDS).find(k => k.toLowerCase() === trimmed.toLowerCase());
  return key ? TR_CITY_COORDS[key] : null;
}
