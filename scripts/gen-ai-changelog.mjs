/**
 * AI bağlam paneli için "Son Değişiklikler"i git commit geçmişinden üretir.
 * prebuild olarak koşar (npm run build öncesi) → her deploy'da otomatik yenilenir,
 * yani yaptığımız her commit panele otomatik yansır.
 *
 * Build-safe: git yoksa/başarısızsa mevcut dosyayı KORUR ve exit 0 (build'i kırmaz).
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const SEP = String.fromCharCode(31); // unit separator — commit metninde geçmez

try {
  const raw = execSync(`git log -n 25 --date=short --pretty=format:%h${SEP}%ad${SEP}%s`, { encoding: 'utf8' });
  const entries = raw.split('\n').filter(Boolean).map((line) => {
    const [hash, date, subject] = line.split(SEP);
    return { hash, date, subject };
  });
  const generated = execSync('git log -1 --date=short --pretty=format:%ad', { encoding: 'utf8' }).trim();

  const content =
    '// AUTO-GENERATED by scripts/gen-ai-changelog.mjs (prebuild). Elle duzenleme.\n' +
    `export const AI_CHANGELOG_GENERATED = ${JSON.stringify(generated)};\n` +
    'export interface AiChangelogEntry { hash: string; date: string; subject: string; }\n' +
    `export const AI_CHANGELOG: AiChangelogEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
  writeFileSync('src/lib/ai-changelog.ts', content);
  console.log(`[gen-ai-changelog] ${entries.length} commit yazildi (son: ${generated}).`);
} catch (err) {
  console.warn('[gen-ai-changelog] git yok/basarisiz — mevcut dosya korunuyor:', err?.message || err);
  process.exit(0);
}
